#!/usr/bin/env python3
"""Experiment 7 - WBS, activity network, CPM and Gantt chart for LabSense.

Single source of truth for the project schedule. Edit TASKS (durations or
predecessors) and re-run; it recomputes the critical path and regenerates:

    exp7-wbs.puml               work breakdown structure
    exp7-activity-network.puml  activity-on-node network with ES/EF/LS/LF/slack
    exp7-gantt.puml             Gantt chart (critical path in red)
    exp7-cpm-table.md           CPM table for the write-up

Usage:  python3 docs/diagrams/exp7_schedule.py
"""

